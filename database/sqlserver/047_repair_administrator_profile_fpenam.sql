/* Repara el perfil Administrador y lo aplica a fpenam.
   Ejecutar en SQL Server contra la base cxView. Es idempotente. */
USE [cxView];
GO
SET NOCOUNT ON;
SET XACT_ABORT ON;
BEGIN TRANSACTION;

DECLARE @profile varchar(36), @user varchar(36), @app varchar(36);
SELECT TOP (1) @user=IDUSER FROM dbo.TAS006 WHERE LOWER(LTRIM(RTRIM(USUARIO)))='fpenam' AND ESTUSER='A' AND SACRG=1;
IF @user IS NULL THROW 51471, 'No se encontró el usuario activo fpenam.', 1;

SELECT TOP (1) @profile=IDPERFIL FROM dbo.TAS017 WHERE UPPER(LTRIM(RTRIM(NOMPERFIL)))='ADMINISTRADOR';
SELECT TOP (1) @app=IDAPP FROM dbo.TAS002 WHERE SACRG=1 ORDER BY IDAPP;

IF @profile IS NULL
BEGIN
  SET @profile=CONVERT(varchar(36),NEWID());
  INSERT dbo.TAS017(IDPERFIL,IDAPP,NOMPERFIL,DESCPERFIL,ESTPERFIL,SACRG,CUSCRT,FCHHRACRT)
  VALUES(@profile,@app,'ADMINISTRADOR','Acceso total al sistema','A',1,'ADMIN',SYSDATETIME());
END
ELSE
  UPDATE dbo.TAS017 SET DESCPERFIL='Acceso total al sistema',ESTPERFIL='A',SACRG=1,CULUSA='ADMIN',FCHHRAACT=SYSDATETIME() WHERE IDPERFIL=@profile;

DELETE FROM dbo.TAS018 WHERE IDPERFIL=@profile;
DELETE FROM dbo.TAS019 WHERE IDPERFIL=@profile;
DELETE FROM dbo.TAS020 WHERE IDPERFIL=@profile;
DELETE FROM dbo.TAS021 WHERE IDPERFIL=@profile;
DELETE FROM dbo.TAS022 WHERE IDPERFIL=@profile;

INSERT dbo.TAS018(IDPRFLMOD,IDPERFIL,IDMOD,ESTPRFLMOD,SACRG,CUSCRT,FCHHRACRT)
SELECT CONVERT(varchar(36),NEWID()),@profile,IDMOD,'A',1,'ADMIN',SYSDATETIME() FROM dbo.TAS007 WHERE ESTMOD='A' AND SACRG=1;
INSERT dbo.TAS019(IDPRFLMNU,IDPERFIL,IDMENU,ESTPRFLMNU,SACRG,CUSCRT,FCHHRACRT)
SELECT CONVERT(varchar(36),NEWID()),@profile,IDMENU,'A',1,'ADMIN',SYSDATETIME() FROM dbo.TAS009 WHERE ESTMENU='A' AND SACRG=1;
INSERT dbo.TAS020(IDPRFLSM,IDPERFIL,IDSUBMENU,ESTPRFLMNU,SACRG,CUSCRT,FCHHRACRT)
SELECT CONVERT(varchar(36),NEWID()),@profile,IDSUBMENU,'A',1,'ADMIN',SYSDATETIME() FROM dbo.TAS011 WHERE ESTSUBMNU='A' AND SACRG=1;
INSERT dbo.TAS021(IDPRFLSMSN,IDPERFIL,IDSMSN,ESTPRFLMNU,SACRG,CUSCRT,FCHHRACRT)
SELECT CONVERT(varchar(36),NEWID()),@profile,IDSMSN,'A',1,'ADMIN',SYSDATETIME() FROM dbo.TAS013 WHERE ESTSMSN='A' AND SACRG=1;
INSERT dbo.TAS022(IDPRFLOPC,IDPERFIL,IDOPCFOMR,ESTPRFLMNU,SACRG,CUSCRT,FCHHRACRT)
SELECT CONVERT(varchar(36),NEWID()),@profile,IDOPCFOMR,'A',1,'ADMIN',SYSDATETIME() FROM dbo.TAS015 WHERE ESTOPC='A' AND SACRG=1;

EXEC dbo.SP_TAS017_APLICAR_PERFIL_USUARIO @idperfil=@profile,@iduser=@user,@usuario='ADMIN';
COMMIT TRANSACTION;
GO
