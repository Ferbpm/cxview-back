CREATE OR ALTER PROCEDURE usp_security_permission_has_code
  @p_user_id varchar(36), @p_code varchar(50)
AS
BEGIN
 SET NOCOUNT ON;
 SELECT CONVERT(int,CASE WHEN EXISTS (
   SELECT 1 FROM dbo.TAS015 o JOIN dbo.TAS016 u ON u.IDOPCFOMR=o.IDOPCFOMR
   WHERE u.IDUSER=@p_user_id AND o.NOMOPC=@p_code AND o.ESTOPC='A' AND o.SACRG=1 AND u.ESTOPC='A' AND u.SACRG=1
 ) OR EXISTS (
   SELECT 1 FROM dbo.TAS022 po JOIN dbo.TAS025 pu ON pu.IDPERFIL=po.IDPERFIL JOIN dbo.TAS015 o ON o.IDOPCFOMR=po.IDOPCFOMR
   WHERE pu.IDUSER=@p_user_id AND o.NOMOPC=@p_code AND o.ESTOPC='A' AND o.SACRG=1 AND po.SACRG=1
 ) THEN 1 ELSE 0 END) AS HAS_PERMISSION;
END;
GO
