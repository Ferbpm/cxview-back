-- Business units assigned to users and query for the module-selection view.
USE [cxView];
GO

IF OBJECT_ID(N'[dbo].[TAM022]', N'U') IS NULL
BEGIN
  CREATE TABLE [dbo].[TAM022] (
    [IDUSERUNDIV] varchar(36) NOT NULL CONSTRAINT [DF_TAM022_IDUSERUNDIV] DEFAULT CONVERT(varchar(36), NEWID()),
    [IDUSER] varchar(36) NOT NULL,
    [IDUNDIV] varchar(36) NOT NULL,
    [ESTUSERUNDIV] varchar(1) NOT NULL CONSTRAINT [DF_TAM022_ESTUSERUNDIV] DEFAULT 'A',
    [SACRG] bit NOT NULL CONSTRAINT [DF_TAM022_SACRG] DEFAULT 1,
    [CUSCRT] varchar(20) NOT NULL,
    [FCHHRACRT] datetime2(6) NULL CONSTRAINT [DF_TAM022_FCHHRACRT] DEFAULT SYSDATETIME(),
    [CULUSA] varchar(20) NULL,
    [FCHHRAACT] datetime2(6) NULL,
    CONSTRAINT [PK_TAM022] PRIMARY KEY ([IDUSERUNDIV]),
    CONSTRAINT [UX_TAM022_IDUSER_IDUNDIV] UNIQUE ([IDUSER], [IDUNDIV]),
    CONSTRAINT [FK_TAM022_TAS006] FOREIGN KEY ([IDUSER]) REFERENCES [dbo].[TAS006] ([IDUSER]),
    CONSTRAINT [FK_TAM022_TAM042] FOREIGN KEY ([IDUNDIV]) REFERENCES [dbo].[TAM042] ([IDUNDIV])
  );
END;
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'[dbo].[TAM022]') AND name=N'IX_TAM022_IDUNDIV')
  CREATE INDEX [IX_TAM022_IDUNDIV] ON [dbo].[TAM022] ([IDUNDIV]);
GO

UPDATE a
SET [ESTUSERUNDIV] = 'A', [SACRG] = 1, [CULUSA] = 'FPENAM', [FCHHRAACT] = SYSDATETIME()
FROM [dbo].[TAM022] a
JOIN [dbo].[TAS006] u ON u.[IDUSER] = a.[IDUSER] AND LOWER(u.[USUARIO]) = 'fpenam'
JOIN [dbo].[TAM042] b ON b.[IDUNDIV] = a.[IDUNDIV] AND b.[ESTUNDIV] = 'A' AND b.[SACRG] = 1
WHERE a.[ESTUSERUNDIV] <> 'A' OR a.[SACRG] <> 1;
GO

INSERT INTO [dbo].[TAM022] ([IDUSER], [IDUNDIV], [ESTUSERUNDIV], [SACRG], [CUSCRT])
SELECT u.[IDUSER], b.[IDUNDIV], 'A', 1, 'FPENAM'
FROM [dbo].[TAS006] u
JOIN [dbo].[TAM042] b ON b.[ESTUNDIV] = 'A' AND b.[SACRG] = 1
WHERE LOWER(u.[USUARIO]) = 'fpenam'
  AND u.[ESTUSER] = 'A' AND u.[SACRG] = 1
  AND NOT EXISTS (
    SELECT 1 FROM [dbo].[TAM022] a WHERE a.[IDUSER] = u.[IDUSER] AND a.[IDUNDIV] = b.[IDUNDIV]
  );
GO

CREATE OR ALTER PROCEDURE [dbo].[SP_TAM022_LISTAR_UNIDADES_NEGOCIO_USUARIO]
  @usuario varchar(20)
AS
BEGIN
  SET NOCOUNT ON;

  SELECT
    b.[IDUNDIV],
    b.[NOMUNDIV],
    b.[DSCUNDIV],
    b.[IDREGVTA]
  FROM [dbo].[TAS006] u
  JOIN [dbo].[TAM022] a ON a.[IDUSER] = u.[IDUSER]
    AND a.[ESTUSERUNDIV] = 'A' AND a.[SACRG] = 1
  JOIN [dbo].[TAM042] b ON b.[IDUNDIV] = a.[IDUNDIV]
    AND b.[ESTUNDIV] = 'A' AND b.[SACRG] = 1
  WHERE u.[USUARIO] = LTRIM(RTRIM(@usuario))
    AND u.[ESTUSER] = 'A' AND u.[SACRG] = 1
  ORDER BY b.[NOMUNDIV];
END;
GO
