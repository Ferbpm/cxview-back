DECLARE @userId varchar(36)=(SELECT TOP(1) IDUSER FROM dbo.TAS006 WHERE LOWER(USUARIO)='fpenam' AND ESTUSER='A' AND SACRG=1);
IF @userId IS NULL THROW 50020,'No se encontró el usuario activo fpenam.',1;

UPDATE a SET ESTOPC='A',SACRG=1,CULUSA='ADMIN',FCHHRAACT=SYSDATETIME()
FROM dbo.TAS016 a JOIN dbo.TAS015 o ON o.IDOPCFOMR=a.IDOPCFOMR
WHERE a.IDUSER=@userId AND o.ESTOPC='A' AND o.SACRG=1;

INSERT dbo.TAS016(IDOPCFORMUSU,IDOPCFOMR,IDUSER,ESTOPC,SACRG,CUSCRT,FCHHRACRT)
SELECT CONVERT(varchar(36),NEWID()),o.IDOPCFOMR,@userId,'A',1,'ADMIN',SYSDATETIME()
FROM dbo.TAS015 o
WHERE o.ESTOPC='A' AND o.SACRG=1
AND NOT EXISTS(SELECT 1 FROM dbo.TAS016 a WHERE a.IDUSER=@userId AND a.IDOPCFOMR=o.IDOPCFOMR);
GO
