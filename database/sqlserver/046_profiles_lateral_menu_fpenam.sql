/* Seguridad > Perfiles como menú lateral independiente de Maestros. */
USE [cxView];
GO
SET NOCOUNT ON;

DECLARE @user varchar(36), @module varchar(36), @menu varchar(36)='a9fd8380-1005-4b11-9422-523100ee0005', @submenu varchar(36)='a9fd8380-1005-4b11-9422-523100ee0004';
SELECT TOP (1) @user=IDUSER FROM dbo.TAS006 WHERE LOWER(LTRIM(RTRIM(USUARIO)))='fpenam' AND ESTUSER='A' AND SACRG=1;
SELECT TOP (1) @module=IDMOD FROM dbo.TAS007 WHERE UPPER(LTRIM(RTRIM(NOMMOD)))='SEGURIDAD' AND ESTMOD='A' AND SACRG=1;
IF @user IS NULL THROW 51301,'No se encontró el usuario activo fpenam.',1;
IF @module IS NULL THROW 51302,'No se encontró el módulo activo SEGURIDAD.',1;

IF NOT EXISTS (SELECT 1 FROM dbo.TAS009 WHERE IDMENU=@menu)
  INSERT dbo.TAS009(IDMENU,IDMOD,NOMMENU,DESCMENU,ESTMENU,SACRG,CUSCRT,FCHHRACRT)
  VALUES(@menu,@module,'PERFILES','Administración de perfiles de usuario','A',1,'ADMIN',SYSDATETIME());
ELSE
  UPDATE dbo.TAS009 SET IDMOD=@module,NOMMENU='PERFILES',DESCMENU='Administración de perfiles de usuario',ESTMENU='A',SACRG=1,CULUSA='ADMIN',FCHHRAACT=SYSDATETIME() WHERE IDMENU=@menu;

/* Se conserva el identificador del submenú para no romper rutas ni opciones existentes. */
IF NOT EXISTS (SELECT 1 FROM dbo.TAS011 WHERE IDSUBMENU=@submenu)
  INSERT dbo.TAS011(IDSUBMENU,IDMENU,NOMSUBMNU,DESCSUBMNU,ESTSUBMNU,SACRG,CUSCRT,FCHHRACRT)
  VALUES(@submenu,@menu,'PERFILES','Mantenimiento de perfiles de usuario','A',1,'ADMIN',SYSDATETIME());
ELSE
  UPDATE dbo.TAS011 SET IDMENU=@menu,NOMSUBMNU='PERFILES',DESCSUBMNU='Mantenimiento de perfiles de usuario',ESTSUBMNU='A',SACRG=1,CULUSA='ADMIN',FCHHRAACT=SYSDATETIME() WHERE IDSUBMENU=@submenu;

IF NOT EXISTS (SELECT 1 FROM dbo.TAS008 WHERE IDUSER=@user AND IDMOD=@module)
  INSERT dbo.TAS008(IDMODUSU,IDMOD,IDUSER,ESTMODUSU,SACRG,CUSCRT,FCHHRACRT) VALUES(CONVERT(varchar(36),NEWID()),@module,@user,'A',1,'ADMIN',SYSDATETIME());
ELSE UPDATE dbo.TAS008 SET ESTMODUSU='A',SACRG=1,CULUSA='ADMIN',FCHHRAACT=SYSDATETIME() WHERE IDUSER=@user AND IDMOD=@module;

IF NOT EXISTS (SELECT 1 FROM dbo.TAS010 WHERE IDUSER=@user AND IDMENU=@menu)
  INSERT dbo.TAS010(IDMENUUSU,IDMENU,IDUSER,ESTMENUUSU,SACRG,CUSCRT,FCHHRACRT) VALUES(CONVERT(varchar(36),NEWID()),@menu,@user,'A',1,'ADMIN',SYSDATETIME());
ELSE UPDATE dbo.TAS010 SET ESTMENUUSU='A',SACRG=1,CULUSA='ADMIN',FCHHRAACT=SYSDATETIME() WHERE IDUSER=@user AND IDMENU=@menu;

IF NOT EXISTS (SELECT 1 FROM dbo.TAS012 WHERE IDUSER=@user AND IDSUBMENU=@submenu)
  INSERT dbo.TAS012(IDSMUSER,IDSUBMENU,IDUSER,ESTSMUSER,SACRG,CUSCRT,FCHHRACRT) VALUES(CONVERT(varchar(36),NEWID()),@submenu,@user,'A',1,'ADMIN',SYSDATETIME());
ELSE UPDATE dbo.TAS012 SET ESTSMUSER='A',SACRG=1,CULUSA='ADMIN',FCHHRAACT=SYSDATETIME() WHERE IDUSER=@user AND IDSUBMENU=@submenu;

DECLARE @actions TABLE (code varchar(50), description varchar(50));
INSERT @actions VALUES
('profiles.filter','Filtrar perfiles'),('profiles.create','Nuevo perfil'),('profiles.update','Editar perfil'),('profiles.delete','Dar de baja perfil'),('profiles.assign','Aplicar perfil a usuario');

INSERT dbo.TAS015(IDOPCFOMR,IDSUBMENU,NOMOPC,DESCOPC,ESTOPC,SACRG,CUSCRT,FCHHRACRT)
SELECT CONVERT(varchar(36),NEWID()),@submenu,a.code,a.description,'A',1,'ADMIN',SYSDATETIME()
FROM @actions a
WHERE NOT EXISTS (SELECT 1 FROM dbo.TAS015 o WHERE o.IDSUBMENU=@submenu AND o.NOMOPC=a.code);

UPDATE o SET IDSUBMENU=@submenu,ESTOPC='A',SACRG=1,CULUSA='ADMIN',FCHHRAACT=SYSDATETIME()
FROM dbo.TAS015 o JOIN @actions a ON a.code=o.NOMOPC;

INSERT dbo.TAS016(IDOPCFORMUSU,IDOPCFOMR,IDUSER,ESTOPC,SACRG,CUSCRT,FCHHRACRT)
SELECT CONVERT(varchar(36),NEWID()),o.IDOPCFOMR,@user,'A',1,'ADMIN',SYSDATETIME()
FROM dbo.TAS015 o JOIN @actions a ON a.code=o.NOMOPC
WHERE o.IDSUBMENU=@submenu AND NOT EXISTS (SELECT 1 FROM dbo.TAS016 x WHERE x.IDUSER=@user AND x.IDOPCFOMR=o.IDOPCFOMR);

UPDATE x SET ESTOPC='A',SACRG=1,CULUSA='ADMIN',FCHHRAACT=SYSDATETIME()
FROM dbo.TAS016 x JOIN dbo.TAS015 o ON o.IDOPCFOMR=x.IDOPCFOMR
WHERE x.IDUSER=@user AND o.IDSUBMENU=@submenu;
GO
