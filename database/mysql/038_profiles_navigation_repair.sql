-- Repair navigation chain for Seguridad > Maestros > Perfiles (MySQL 8).
USE `cxView`;

SET @submenu='a9fd8380-1005-4b11-9422-523100ee0004';
SET @user=(SELECT `IDUSER` FROM `TAS006` WHERE LOWER(TRIM(`USUARIO`))='fpenam' AND `ESTUSER`='A' AND `SACRG`=1 LIMIT 1);
SET @module=(SELECT `IDMOD` FROM `TAS007` WHERE UPPER(TRIM(`NOMMOD`))='SEGURIDAD' AND `ESTMOD`='A' AND `SACRG`=1 LIMIT 1);
SET @menu=(SELECT `IDMENU` FROM `TAS009` WHERE `IDMOD`=@module AND UPPER(TRIM(`NOMMENU`))='MAESTROS' AND `ESTMENU`='A' AND `SACRG`=1 LIMIT 1);

INSERT INTO `TAS011` (`IDSUBMENU`,`IDMENU`,`NOMSUBMNU`,`DESCSUBMNU`,`ESTSUBMNU`,`SACRG`,`CUSCRT`,`FCHHRACRT`)
SELECT @submenu,@menu,'PERFILES','Mantenimiento de perfiles de usuario','A',1,'ADMIN',CURRENT_TIMESTAMP(6)
WHERE @user IS NOT NULL AND @module IS NOT NULL AND @menu IS NOT NULL
  AND NOT EXISTS(SELECT 1 FROM `TAS011` WHERE `IDSUBMENU`=@submenu);
UPDATE `TAS011` SET `IDMENU`=@menu,`NOMSUBMNU`='PERFILES',`DESCSUBMNU`='Mantenimiento de perfiles de usuario',`ESTSUBMNU`='A',`SACRG`=1,`CULUSA`='ADMIN',`FCHHRAACT`=CURRENT_TIMESTAMP(6)
WHERE @menu IS NOT NULL AND `IDSUBMENU`=@submenu;

UPDATE `TAS008` SET `ESTMODUSU`='A',`SACRG`=1,`CULUSA`='ADMIN',`FCHHRAACT`=CURRENT_TIMESTAMP(6) WHERE `IDUSER`=@user AND `IDMOD`=@module;
INSERT INTO `TAS008` (`IDMODUSU`,`IDMOD`,`IDUSER`,`ESTMODUSU`,`SACRG`,`CUSCRT`,`FCHHRACRT`)
SELECT UUID(),@module,@user,'A',1,'ADMIN',CURRENT_TIMESTAMP(6) WHERE @user IS NOT NULL AND @module IS NOT NULL AND NOT EXISTS(SELECT 1 FROM `TAS008` WHERE `IDUSER`=@user AND `IDMOD`=@module);
UPDATE `TAS010` SET `ESTMENUUSU`='A',`SACRG`=1,`CULUSA`='ADMIN',`FCHHRAACT`=CURRENT_TIMESTAMP(6) WHERE `IDUSER`=@user AND `IDMENU`=@menu;
INSERT INTO `TAS010` (`IDMENUUSU`,`IDMENU`,`IDUSER`,`ESTMENUUSU`,`SACRG`,`CUSCRT`,`FCHHRACRT`)
SELECT UUID(),@menu,@user,'A',1,'ADMIN',CURRENT_TIMESTAMP(6) WHERE @user IS NOT NULL AND @menu IS NOT NULL AND NOT EXISTS(SELECT 1 FROM `TAS010` WHERE `IDUSER`=@user AND `IDMENU`=@menu);
UPDATE `TAS012` SET `ESTSMUSER`='A',`SACRG`=1,`CULUSA`='ADMIN',`FCHHRAACT`=CURRENT_TIMESTAMP(6) WHERE `IDUSER`=@user AND `IDSUBMENU`=@submenu;
INSERT INTO `TAS012` (`IDSMUSER`,`IDSUBMENU`,`IDUSER`,`ESTSMUSER`,`SACRG`,`CUSCRT`,`FCHHRACRT`)
SELECT UUID(),@submenu,@user,'A',1,'ADMIN',CURRENT_TIMESTAMP(6) WHERE @user IS NOT NULL AND EXISTS(SELECT 1 FROM `TAS011` WHERE `IDSUBMENU`=@submenu) AND NOT EXISTS(SELECT 1 FROM `TAS012` WHERE `IDUSER`=@user AND `IDSUBMENU`=@submenu);

DROP PROCEDURE IF EXISTS `SP_TAS011_LISTAR_SUBMENUS_USUARIO_MENU`;
DELIMITER $$
CREATE PROCEDURE `SP_TAS011_LISTAR_SUBMENUS_USUARIO_MENU`(IN usuario varchar(20),IN menu varchar(36))
READS SQL DATA
BEGIN
  SELECT DISTINCT s.`IDSUBMENU`,s.`NOMSUBMNU`,s.`DESCSUBMNU`
  FROM `TAS006` u
  JOIN `TAS008` um ON um.`IDUSER`=u.`IDUSER` AND um.`ESTMODUSU`='A' AND um.`SACRG`=1
  JOIN `TAS009` m ON m.`IDMOD`=um.`IDMOD` AND m.`IDMENU`=TRIM(menu) AND m.`ESTMENU`='A' AND m.`SACRG`=1
  JOIN `TAS010` u_m ON u_m.`IDUSER`=u.`IDUSER` AND u_m.`IDMENU`=m.`IDMENU` AND u_m.`ESTMENUUSU`='A' AND u_m.`SACRG`=1
  JOIN `TAS011` s ON s.`IDMENU`=m.`IDMENU` AND s.`ESTSUBMNU`='A' AND s.`SACRG`=1
  JOIN `TAS012` u_s ON u_s.`IDUSER`=u.`IDUSER` AND u_s.`IDSUBMENU`=s.`IDSUBMENU` AND u_s.`ESTSMUSER`='A' AND u_s.`SACRG`=1
  WHERE u.`USUARIO`=TRIM(usuario) AND u.`ESTUSER`='A' AND u.`SACRG`=1
  ORDER BY s.`NOMSUBMNU`;
END$$
DELIMITER ;
