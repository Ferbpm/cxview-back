-- Password reset for TAS006 users (MySQL 8).
-- `clave` NULL or empty resets to the default password 123456.
-- Any non-empty `clave` must be a PBKDF2-SHA512 hash created by the backend.
USE `cxView`;

DROP PROCEDURE IF EXISTS `SP_TAS006_REINICIAR_CLAVE`;
DELIMITER $$
CREATE PROCEDURE `SP_TAS006_REINICIAR_CLAVE`(
  IN iduser varchar(36),
  IN clave varbinary(128),
  IN usuario varchar(20)
)
MODIFIES SQL DATA
BEGIN
  DECLARE clave_defecto varbinary(128);
  SET clave_defecto = UNHEX('70626b6466322d73686135313224323130303030244d66376f4136632b2b375a71765748737551303672444846654f4b3375534e7164635a534254446872496b3d2459352f4b62323652705a323770767159316e374f73446b7235782b666f343373476c514641666d727949673d');

  UPDATE `TAS006`
  SET `CLAVE` = CASE WHEN clave IS NULL OR OCTET_LENGTH(clave) = 0 THEN clave_defecto ELSE clave END,
      `FLGACTPASS` = CASE WHEN clave IS NULL OR OCTET_LENGTH(clave) = 0 THEN 1 ELSE 0 END,
      `CULUSA` = NULLIF(TRIM(usuario), ''),
      `FCHHRAACT` = CURRENT_TIMESTAMP(6)
  WHERE `IDUSER` = TRIM(iduser)
    AND `ESTUSER` = 'A'
    AND `SACRG` = 1;

  SELECT `IDUSER`, `USUARIO`, `ESTUSER`, `FLGACTPASS`, `CULUSA`, `FCHHRAACT`,
         ROW_COUNT() AS `FILASAFECTADAS`
  FROM `TAS006`
  WHERE `IDUSER` = TRIM(iduser)
    AND `ESTUSER` = 'A'
    AND `SACRG` = 1;
END$$
DELIMITER ;
