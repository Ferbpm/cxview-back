-- List active sites assigned to an active user.
USE `cxView`;

DROP PROCEDURE IF EXISTS `SP_TAS024_LISTAR_SEDES_USUARIO`;
DELIMITER $$
CREATE PROCEDURE `SP_TAS024_LISTAR_SEDES_USUARIO`(IN usuario varchar(20))
READS SQL DATA
BEGIN
  SELECT
    s.`IDSEDE`,
    s.`NOMSEDE`,
    s.`NOMABRV`,
    s.`DIRSEDE`,
    s.`TELFSEDE`,
    (s.`IDSEDE` = u.`IDSEDEDEFAULT`) AS `ESPREDETERMINADA`
  FROM `TAS006` u
  JOIN `TAS024` a ON a.`IDUSER` = u.`IDUSER`
    AND a.`ESTSEDEUSER` = 'A' AND a.`SACRG` = 1
  JOIN `TAS023` s ON s.`IDSEDE` = a.`IDSEDE`
    AND s.`ESTSEDE` = 'A' AND s.`SACRG` = 1
  WHERE u.`USUARIO` = TRIM(usuario)
    AND u.`ESTUSER` = 'A' AND u.`SACRG` = 1
  ORDER BY `ESPREDETERMINADA` DESC, s.`NOMSEDE`;
END$$
DELIMITER ;

