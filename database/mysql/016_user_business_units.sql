-- Business units assigned to users and query for the module-selection view.
USE `cxView`;

CREATE TABLE IF NOT EXISTS `TAM022` (
  `IDUSERUNDIV` varchar(36) NOT NULL DEFAULT (UUID()),
  `IDUSER` varchar(36) NOT NULL,
  `IDUNDIV` varchar(36) NOT NULL,
  `ESTUSERUNDIV` varchar(1) NOT NULL DEFAULT 'A',
  `SACRG` bit(1) NOT NULL DEFAULT b'1',
  `CUSCRT` varchar(20) NOT NULL,
  `FCHHRACRT` datetime(6) NULL DEFAULT CURRENT_TIMESTAMP(6),
  `CULUSA` varchar(20) NULL,
  `FCHHRAACT` datetime(6) NULL,
  CONSTRAINT `PK_TAM022` PRIMARY KEY (`IDUSERUNDIV`),
  CONSTRAINT `UX_TAM022_IDUSER_IDUNDIV` UNIQUE (`IDUSER`, `IDUNDIV`),
  KEY `IX_TAM022_IDUNDIV` (`IDUNDIV`),
  CONSTRAINT `FK_TAM022_TAS006` FOREIGN KEY (`IDUSER`) REFERENCES `TAS006` (`IDUSER`),
  CONSTRAINT `FK_TAM022_TAM042` FOREIGN KEY (`IDUNDIV`) REFERENCES `TAM042` (`IDUNDIV`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

UPDATE `TAM022` a
JOIN `TAS006` u ON u.`IDUSER` = a.`IDUSER` AND LOWER(u.`USUARIO`) = 'fpenam'
JOIN `TAM042` b ON b.`IDUNDIV` = a.`IDUNDIV` AND b.`ESTUNDIV` = 'A' AND b.`SACRG` = 1
SET a.`ESTUSERUNDIV` = 'A', a.`SACRG` = b'1', a.`CULUSA` = 'FPENAM', a.`FCHHRAACT` = CURRENT_TIMESTAMP(6)
WHERE a.`ESTUSERUNDIV` <> 'A' OR a.`SACRG` <> 1;

INSERT INTO `TAM022` (`IDUSER`, `IDUNDIV`, `ESTUSERUNDIV`, `SACRG`, `CUSCRT`)
SELECT u.`IDUSER`, b.`IDUNDIV`, 'A', b'1', 'FPENAM'
FROM `TAS006` u
JOIN `TAM042` b ON b.`ESTUNDIV` = 'A' AND b.`SACRG` = 1
WHERE LOWER(u.`USUARIO`) = 'fpenam'
  AND u.`ESTUSER` = 'A' AND u.`SACRG` = 1
  AND NOT EXISTS (
    SELECT 1 FROM `TAM022` a WHERE a.`IDUSER` = u.`IDUSER` AND a.`IDUNDIV` = b.`IDUNDIV`
  );

DROP PROCEDURE IF EXISTS `SP_TAM022_LISTAR_UNIDADES_NEGOCIO_USUARIO`;
DELIMITER $$
CREATE PROCEDURE `SP_TAM022_LISTAR_UNIDADES_NEGOCIO_USUARIO`(IN usuario varchar(20))
READS SQL DATA
BEGIN
  SELECT
    b.`IDUNDIV`,
    b.`NOMUNDIV`,
    b.`DSCUNDIV`,
    b.`IDREGVTA`
  FROM `TAS006` u
  JOIN `TAM022` a ON a.`IDUSER` = u.`IDUSER`
    AND a.`ESTUSERUNDIV` = 'A' AND a.`SACRG` = 1
  JOIN `TAM042` b ON b.`IDUNDIV` = a.`IDUNDIV`
    AND b.`ESTUNDIV` = 'A' AND b.`SACRG` = 1
  WHERE u.`USUARIO` = TRIM(usuario)
    AND u.`ESTUSER` = 'A' AND u.`SACRG` = 1
  ORDER BY b.`NOMUNDIV`;
END$$
DELIMITER ;
