UPDATE `TAS012` a
JOIN `TAS006` u ON u.`IDUSER` = a.`IDUSER` AND LOWER(u.`USUARIO`) = 'fpenam'
JOIN `TAS011` s ON s.`IDSUBMENU` = a.`IDSUBMENU` AND s.`IDMENU` = 'd6d3b9db-c95f-4d24-b5b7-ea15fd92a908'
SET a.`ESTSMUSER` = 'A', a.`SACRG` = 1, a.`CULUSA` = 'ADMIN', a.`FCHHRAACT` = CURRENT_TIMESTAMP(6)
WHERE s.`NOMSUBMNU` IN ('EMPRESA','APLICACIONES EMPRESARIALES','DOMINIOS DE LA EMPRESA','ÁREAS DE LA EMPRESA','ROLES DE LAS ÁREAS DE LA EMPRESA','USUARIOS','MÓDULOS POR APLICACIONES')
  AND (a.`ESTSMUSER` <> 'A' OR a.`SACRG` <> 1);

INSERT INTO `TAS012` (`IDSMUSER`,`IDSUBMENU`,`IDUSER`,`ESTSMUSER`,`SACRG`,`CUSCRT`,`FCHHRACRT`)
SELECT UUID(), s.`IDSUBMENU`, u.`IDUSER`, 'A', 1, 'ADMIN', CURRENT_TIMESTAMP(6)
FROM `TAS006` u
JOIN `TAS011` s ON s.`IDMENU` = 'd6d3b9db-c95f-4d24-b5b7-ea15fd92a908'
WHERE LOWER(u.`USUARIO`) = 'fpenam' AND u.`ESTUSER` = 'A' AND u.`SACRG` = 1
  AND s.`NOMSUBMNU` IN ('EMPRESA','APLICACIONES EMPRESARIALES','DOMINIOS DE LA EMPRESA','ÁREAS DE LA EMPRESA','ROLES DE LAS ÁREAS DE LA EMPRESA','USUARIOS','MÓDULOS POR APLICACIONES')
  AND NOT EXISTS (SELECT 1 FROM `TAS012` a WHERE a.`IDSUBMENU` = s.`IDSUBMENU` AND a.`IDUSER` = u.`IDUSER`);
