SET `ESTSUBMNU` = 'A', `SACRG` = 1, `CULUSA` = 'ADMIN', `FCHHRAACT` = CURRENT_TIMESTAMP(6)
WHERE `IDMENU` = 'd6d3b9db-c95f-4d24-b5b7-ea15fd92a908'
