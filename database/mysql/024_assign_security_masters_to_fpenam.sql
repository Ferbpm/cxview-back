-- Assign the Security module, Maestros menu, and Empresa submenu to fpenam.
USE `cxView`;

UPDATE `TAS008` a
JOIN `TAS006` u ON u.`IDUSER` = a.`IDUSER` AND LOWER(u.`USUARIO`) = 'fpenam'
JOIN `TAS009` m ON m.`IDMOD` = a.`IDMOD` AND m.`IDMENU` = 'd6d3b9db-c95f-4d24-b5b7-ea15fd92a908'
SET a.`ESTMODUSU` = 'A', a.`SACRG` = 1, a.`CULUSA` = 'ADMIN', a.`FCHHRAACT` = CURRENT_TIMESTAMP(6)
WHERE a.`ESTMODUSU` <> 'A' OR a.`SACRG` <> 1;

INSERT INTO `TAS008` (`IDMODUSU`, `IDMOD`, `IDUSER`, `ESTMODUSU`, `SACRG`, `CUSCRT`, `FCHHRACRT`)
SELECT UUID(), m.`IDMOD`, u.`IDUSER`, 'A', 1, 'ADMIN', CURRENT_TIMESTAMP(6)
FROM `TAS006` u
JOIN `TAS009` m ON m.`IDMENU` = 'd6d3b9db-c95f-4d24-b5b7-ea15fd92a908'
WHERE LOWER(u.`USUARIO`) = 'fpenam' AND u.`ESTUSER` = 'A' AND u.`SACRG` = 1
  AND NOT EXISTS (SELECT 1 FROM `TAS008` a WHERE a.`IDMOD` = m.`IDMOD` AND a.`IDUSER` = u.`IDUSER`);

UPDATE `TAS010` a
JOIN `TAS006` u ON u.`IDUSER` = a.`IDUSER` AND LOWER(u.`USUARIO`) = 'fpenam'
SET a.`ESTMENUUSU` = 'A', a.`SACRG` = 1, a.`CULUSA` = 'ADMIN', a.`FCHHRAACT` = CURRENT_TIMESTAMP(6)
WHERE a.`IDMENU` = 'd6d3b9db-c95f-4d24-b5b7-ea15fd92a908' AND (a.`ESTMENUUSU` <> 'A' OR a.`SACRG` <> 1);

INSERT INTO `TAS010` (`IDMENUUSU`, `IDMENU`, `IDUSER`, `ESTMENUUSU`, `SACRG`, `CUSCRT`, `FCHHRACRT`)
SELECT UUID(), 'd6d3b9db-c95f-4d24-b5b7-ea15fd92a908', u.`IDUSER`, 'A', 1, 'ADMIN', CURRENT_TIMESTAMP(6)
FROM `TAS006` u
WHERE LOWER(u.`USUARIO`) = 'fpenam' AND u.`ESTUSER` = 'A' AND u.`SACRG` = 1
  AND NOT EXISTS (SELECT 1 FROM `TAS010` a WHERE a.`IDMENU` = 'd6d3b9db-c95f-4d24-b5b7-ea15fd92a908' AND a.`IDUSER` = u.`IDUSER`);

UPDATE `TAS012` a
JOIN `TAS006` u ON u.`IDUSER` = a.`IDUSER` AND LOWER(u.`USUARIO`) = 'fpenam'
SET a.`ESTSMUSER` = 'A', a.`SACRG` = 1, a.`CULUSA` = 'ADMIN', a.`FCHHRAACT` = CURRENT_TIMESTAMP(6)
WHERE a.`IDSUBMENU` = '8b1c2c05-5b3d-48b2-9e12-6e2621dcce6b' AND (a.`ESTSMUSER` <> 'A' OR a.`SACRG` <> 1);

INSERT INTO `TAS012` (`IDSMUSER`, `IDSUBMENU`, `IDUSER`, `ESTSMUSER`, `SACRG`, `CUSCRT`, `FCHHRACRT`)
SELECT UUID(), '8b1c2c05-5b3d-48b2-9e12-6e2621dcce6b', u.`IDUSER`, 'A', 1, 'ADMIN', CURRENT_TIMESTAMP(6)
FROM `TAS006` u
WHERE LOWER(u.`USUARIO`) = 'fpenam' AND u.`ESTUSER` = 'A' AND u.`SACRG` = 1
  AND NOT EXISTS (SELECT 1 FROM `TAS012` a WHERE a.`IDSUBMENU` = '8b1c2c05-5b3d-48b2-9e12-6e2621dcce6b' AND a.`IDUSER` = u.`IDUSER`);
