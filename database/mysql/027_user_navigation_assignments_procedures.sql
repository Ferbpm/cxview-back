-- Idempotent user assignments for modules, menus and submenus.
USE `cxView`;

DROP PROCEDURE IF EXISTS `SP_TAS008_ASIGNAR_MODULO_USUARIO`;
DROP PROCEDURE IF EXISTS `SP_TAS010_ASIGNAR_MENU_USUARIO`;
DROP PROCEDURE IF EXISTS `SP_TAS012_ASIGNAR_SUBMENU_USUARIO`;
DELIMITER $$

CREATE PROCEDURE `SP_TAS008_ASIGNAR_MODULO_USUARIO`(IN iduser varchar(36), IN idmodulo varchar(36), IN usuario varchar(20))
BEGIN
  IF NOT EXISTS (SELECT 1 FROM `TAS006` WHERE `IDUSER`=TRIM(iduser) AND `ESTUSER`='A' AND `SACRG`=1) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='El usuario no existe o no está activo.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM `TAS007` WHERE `IDMOD`=TRIM(idmodulo) AND `ESTMOD`='A' AND `SACRG`=1) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='El módulo no existe o no está activo.'; END IF;
  START TRANSACTION;
  IF EXISTS (SELECT 1 FROM `TAS008` WHERE `IDUSER`=TRIM(iduser) AND `IDMOD`=TRIM(idmodulo)) THEN
    UPDATE `TAS008` SET `ESTMODUSU`='A',`SACRG`=1,`CULUSA`=NULLIF(TRIM(usuario),''),`FCHHRAACT`=CURRENT_TIMESTAMP(6) WHERE `IDUSER`=TRIM(iduser) AND `IDMOD`=TRIM(idmodulo);
  ELSE
    INSERT INTO `TAS008`(`IDMODUSU`,`IDMOD`,`IDUSER`,`ESTMODUSU`,`SACRG`,`CUSCRT`,`FCHHRACRT`) VALUES(UUID(),TRIM(idmodulo),TRIM(iduser),'A',1,NULLIF(TRIM(usuario),''),CURRENT_TIMESTAMP(6));
  END IF;
  COMMIT;
  SELECT `IDMODUSU`,`IDMOD`,`IDUSER`,`ESTMODUSU`,`SACRG`,`CUSCRT`,`FCHHRACRT`,`CULUSA`,`FCHHRAACT` FROM `TAS008` WHERE `IDUSER`=TRIM(iduser) AND `IDMOD`=TRIM(idmodulo) AND `ESTMODUSU`='A' AND `SACRG`=1 ORDER BY `FCHHRAACT` DESC,`FCHHRACRT` DESC LIMIT 1;
END$$

CREATE PROCEDURE `SP_TAS010_ASIGNAR_MENU_USUARIO`(IN iduser varchar(36), IN idmenu varchar(36), IN usuario varchar(20))
BEGIN
  IF NOT EXISTS (SELECT 1 FROM `TAS006` WHERE `IDUSER`=TRIM(iduser) AND `ESTUSER`='A' AND `SACRG`=1) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='El usuario no existe o no está activo.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM `TAS009` menu JOIN `TAS007` module ON module.`IDMOD`=menu.`IDMOD` JOIN `TAS008` assignment ON assignment.`IDMOD`=module.`IDMOD` AND assignment.`IDUSER`=TRIM(iduser) AND assignment.`ESTMODUSU`='A' AND assignment.`SACRG`=1 WHERE menu.`IDMENU`=TRIM(idmenu) AND menu.`ESTMENU`='A' AND menu.`SACRG`=1 AND module.`ESTMOD`='A' AND module.`SACRG`=1) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='El menú no está activo o su módulo no está asignado al usuario.'; END IF;
  START TRANSACTION;
  IF EXISTS (SELECT 1 FROM `TAS010` WHERE `IDUSER`=TRIM(iduser) AND `IDMENU`=TRIM(idmenu)) THEN
    UPDATE `TAS010` SET `ESTMENUUSU`='A',`SACRG`=1,`CULUSA`=NULLIF(TRIM(usuario),''),`FCHHRAACT`=CURRENT_TIMESTAMP(6) WHERE `IDUSER`=TRIM(iduser) AND `IDMENU`=TRIM(idmenu);
  ELSE
    INSERT INTO `TAS010`(`IDMENUUSU`,`IDMENU`,`IDUSER`,`ESTMENUUSU`,`SACRG`,`CUSCRT`,`FCHHRACRT`) VALUES(UUID(),TRIM(idmenu),TRIM(iduser),'A',1,NULLIF(TRIM(usuario),''),CURRENT_TIMESTAMP(6));
  END IF;
  COMMIT;
  SELECT `IDMENUUSU`,`IDMENU`,`IDUSER`,`ESTMENUUSU`,`SACRG`,`CUSCRT`,`FCHHRACRT`,`CULUSA`,`FCHHRAACT` FROM `TAS010` WHERE `IDUSER`=TRIM(iduser) AND `IDMENU`=TRIM(idmenu) AND `ESTMENUUSU`='A' AND `SACRG`=1 ORDER BY `FCHHRAACT` DESC,`FCHHRACRT` DESC LIMIT 1;
END$$

CREATE PROCEDURE `SP_TAS012_ASIGNAR_SUBMENU_USUARIO`(IN iduser varchar(36), IN idsubmenu varchar(36), IN usuario varchar(20))
BEGIN
  IF NOT EXISTS (SELECT 1 FROM `TAS006` WHERE `IDUSER`=TRIM(iduser) AND `ESTUSER`='A' AND `SACRG`=1) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='El usuario no existe o no está activo.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM `TAS011` submenu JOIN `TAS009` menu ON menu.`IDMENU`=submenu.`IDMENU` JOIN `TAS007` module ON module.`IDMOD`=menu.`IDMOD` JOIN `TAS008` ma ON ma.`IDMOD`=module.`IDMOD` AND ma.`IDUSER`=TRIM(iduser) AND ma.`ESTMODUSU`='A' AND ma.`SACRG`=1 JOIN `TAS010` mea ON mea.`IDMENU`=menu.`IDMENU` AND mea.`IDUSER`=TRIM(iduser) AND mea.`ESTMENUUSU`='A' AND mea.`SACRG`=1 WHERE submenu.`IDSUBMENU`=TRIM(idsubmenu) AND submenu.`ESTSUBMNU`='A' AND submenu.`SACRG`=1 AND menu.`ESTMENU`='A' AND menu.`SACRG`=1 AND module.`ESTMOD`='A' AND module.`SACRG`=1) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='El submenú no está activo o su menú no está asignado al usuario.'; END IF;
  START TRANSACTION;
  IF EXISTS (SELECT 1 FROM `TAS012` WHERE `IDUSER`=TRIM(iduser) AND `IDSUBMENU`=TRIM(idsubmenu)) THEN
    UPDATE `TAS012` SET `ESTSMUSER`='A',`SACRG`=1,`CULUSA`=NULLIF(TRIM(usuario),''),`FCHHRAACT`=CURRENT_TIMESTAMP(6) WHERE `IDUSER`=TRIM(iduser) AND `IDSUBMENU`=TRIM(idsubmenu);
  ELSE
    INSERT INTO `TAS012`(`IDSMUSER`,`IDSUBMENU`,`IDUSER`,`ESTSMUSER`,`SACRG`,`CUSCRT`,`FCHHRACRT`) VALUES(UUID(),TRIM(idsubmenu),TRIM(iduser),'A',1,NULLIF(TRIM(usuario),''),CURRENT_TIMESTAMP(6));
  END IF;
  COMMIT;
  SELECT `IDSMUSER`,`IDSUBMENU`,`IDUSER`,`ESTSMUSER`,`SACRG`,`CUSCRT`,`FCHHRACRT`,`CULUSA`,`FCHHRAACT` FROM `TAS012` WHERE `IDUSER`=TRIM(iduser) AND `IDSUBMENU`=TRIM(idsubmenu) AND `ESTSMUSER`='A' AND `SACRG`=1 ORDER BY `FCHHRAACT` DESC,`FCHHRACRT` DESC LIMIT 1;
END$$
DELIMITER ;
