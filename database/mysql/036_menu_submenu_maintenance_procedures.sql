CREATE PROCEDURE `SP_TAS011_CONSULTAR_SUBMENUS`(IN idsubmenu varchar(36), IN idmenu varchar(36), IN submenu varchar(50), IN estado varchar(1))
READS SQL DATA
BEGIN
