  WHERE `SACRG`=1
    AND (NULLIF(TRIM(idsubmenu),'') IS NULL OR `IDSUBMENU`=TRIM(idsubmenu))
    AND (NULLIF(TRIM(idmenu),'') IS NULL OR `IDMENU`=TRIM(idmenu))
    AND (NULLIF(TRIM(submenu),'') IS NULL OR `NOMSUBMNU` LIKE CONCAT('%',TRIM(submenu),'%'))
    AND (NULLIF(TRIM(estado),'') IS NULL OR `ESTSUBMNU`=UPPER(TRIM(estado)))
