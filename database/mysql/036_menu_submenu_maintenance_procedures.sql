-- Maintenance procedures for menus (TAS009) and submenus (TAS011).
USE `cxView`;

DROP PROCEDURE IF EXISTS `SP_TAS009_CREAR_MENU`;
DROP PROCEDURE IF EXISTS `SP_TAS009_ACTUALIZAR_MENU`;
DROP PROCEDURE IF EXISTS `SP_TAS009_DAR_BAJA_MENU`;
DROP PROCEDURE IF EXISTS `SP_TAS009_CONSULTAR_MENUS`;
DROP PROCEDURE IF EXISTS `SP_TAS011_CREAR_SUBMENU`;
DROP PROCEDURE IF EXISTS `SP_TAS011_ACTUALIZAR_SUBMENU`;
DROP PROCEDURE IF EXISTS `SP_TAS011_DAR_BAJA_SUBMENU`;
DROP PROCEDURE IF EXISTS `SP_TAS011_CONSULTAR_SUBMENUS`;

DELIMITER $$
CREATE PROCEDURE `SP_TAS009_CREAR_MENU`(IN idmodulo varchar(36), IN menu varchar(50), IN descripcion varchar(50), IN usuario varchar(20))
MODIFIES SQL DATA
BEGIN
  SET @id = UUID();
  INSERT INTO `TAS009` (`IDMENU`,`IDMOD`,`NOMMENU`,`DESCMENU`,`ESTMENU`,`SACRG`,`CUSCRT`,`FCHHRACRT`)
  VALUES (@id,TRIM(idmodulo),TRIM(menu),NULLIF(TRIM(descripcion),''),'A',1,NULLIF(TRIM(usuario),''),CURRENT_TIMESTAMP(6));
  SELECT * FROM `TAS009` WHERE `IDMENU`=@id;
END$$

CREATE PROCEDURE `SP_TAS009_ACTUALIZAR_MENU`(IN idmenu varchar(36), IN idmodulo varchar(36), IN menu varchar(50), IN descripcion varchar(50), IN estado varchar(1), IN usuario varchar(20))
MODIFIES SQL DATA
BEGIN
  UPDATE `TAS009`
  SET `IDMOD`=TRIM(idmodulo), `NOMMENU`=TRIM(menu), `DESCMENU`=NULLIF(TRIM(descripcion),''),
      `ESTMENU`=UPPER(TRIM(estado)), `CULUSA`=NULLIF(TRIM(usuario),''), `FCHHRAACT`=CURRENT_TIMESTAMP(6)
  WHERE `IDMENU`=TRIM(idmenu) AND `SACRG`=1;
  SELECT * FROM `TAS009` WHERE `IDMENU`=TRIM(idmenu) AND `SACRG`=1;
END$$

CREATE PROCEDURE `SP_TAS009_DAR_BAJA_MENU`(IN idmenu varchar(36), IN usuario varchar(20))
MODIFIES SQL DATA
BEGIN
  UPDATE `TAS009` SET `ESTMENU`='I', `SACRG`=0, `CULUSA`=NULLIF(TRIM(usuario),''), `FCHHRAACT`=CURRENT_TIMESTAMP(6)
  WHERE `IDMENU`=TRIM(idmenu) AND `SACRG`=1;
  SELECT ROW_COUNT() AS `FILASAFECTADAS`;
END$$

CREATE PROCEDURE `SP_TAS009_CONSULTAR_MENUS`(IN idmenu varchar(36), IN idmodulo varchar(36), IN menu varchar(50), IN estado varchar(1))
READS SQL DATA
BEGIN
  SELECT * FROM `TAS009`
  WHERE `SACRG`=1
    AND (NULLIF(TRIM(idmenu),'') IS NULL OR `IDMENU`=TRIM(idmenu))
    AND (NULLIF(TRIM(idmodulo),'') IS NULL OR `IDMOD`=TRIM(idmodulo))
    AND (NULLIF(TRIM(menu),'') IS NULL OR `NOMMENU` LIKE CONCAT('%',TRIM(menu),'%'))
    AND (NULLIF(TRIM(estado),'') IS NULL OR `ESTMENU`=UPPER(TRIM(estado)))
  ORDER BY `NOMMENU`;
END$$

CREATE PROCEDURE `SP_TAS011_CREAR_SUBMENU`(IN idmenu varchar(36), IN submenu varchar(50), IN descripcion varchar(100), IN usuario varchar(20))
MODIFIES SQL DATA
BEGIN
