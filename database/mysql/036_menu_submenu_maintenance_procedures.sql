  SELECT * FROM `TAS011` WHERE `IDSUBMENU`=@id;
END$$

CREATE PROCEDURE `SP_TAS011_ACTUALIZAR_SUBMENU`(IN idsubmenu varchar(36), IN idmenu varchar(36), IN submenu varchar(50), IN descripcion varchar(100), IN estado varchar(1), IN usuario varchar(20))
MODIFIES SQL DATA
BEGIN
